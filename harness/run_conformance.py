#!/usr/bin/env python3
"""C11 conformance probes (N1570 clauses 5-7), differential against Clang.

Probes live in conformance/ (described in docs/C11_CONFORMANCE.md):

- conformance/run/*.c: complete programs. Each is compiled by build/hcc
  (IR, then Clang for the object and the link) and by
  `clang -std=c11 -pedantic-errors`. Both must build, and both programs
  must exit with the same status and print the same output. A probe prints
  "FAIL ..." for a self-check that does not hold, which also fails it.
- conformance/diag/*.c: constraint and syntax violations. A file holds
  several cases, each starting with a line `//== CLAUSE description`;
  lines before the first marker are a prelude shared by every case. The
  standard requires a diagnostic (5.1.1.3), so hcc must reject the case or
  print a warning. Clang's behaviour (error, warning or silence) is
  recorded in the results, not required. A marker `//== CLAUSE [policy]
  description` is a case the standard does not require a diagnostic for
  (undefined or implementation-defined behaviour, or an optional feature
  hcc does not provide). hcc's diagnostic is still checked, but these
  cases are counted apart from the required ones.
- Translation-limit programs (5.2.4.1) are generated by this script.
- conformance/known_gaps.txt lists probes hcc is known to fail, with the
  reason. They are reported as KNOWN and do not fail the run.

Results go to standard output, and with --json FILE to a JSON file that
docs/C11_CONFORMANCE.md summarises. Exit status 1 if any probe fails.

Env: CC_UNDER_TEST (default build/hcc), CLANG (default clang), TIMEOUT.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import resource
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HCC = os.environ.get("CC_UNDER_TEST", str(ROOT / "build" / "hcc"))
CLANG = os.environ.get("CLANG", "clang")
TIMEOUT = float(os.environ.get("TIMEOUT", "10"))
# Clang 15+ also makes its "deprecated in all versions of C" warnings for
# unprototyped functions errors under -pedantic-errors; C11 allows them.
CLANG_FLAGS = ["-std=c11", "-pedantic-errors", "-Wno-strict-prototypes", "-Wno-deprecated-non-prototype"]
LIBS = ["-lm", "-pthread"]
MARK = re.compile(r"^//== (\S+) (\[policy\] )?(.*)$")
TIMEOUT_CODE = -999


def limit_memory():
    """Cap each compiler and program at 4 GiB of address space."""
    cap = 4 << 30
    resource.setrlimit(resource.RLIMIT_AS, (cap, cap))


def run(cmd, cwd=None):
    """Exit status, standard output and standard error (each cut at 1 MiB)."""
    with tempfile.TemporaryFile() as out, tempfile.TemporaryFile() as err:
        try:
            p = subprocess.run(cmd, cwd=cwd, stdout=out, stderr=err, timeout=TIMEOUT,
                               stdin=subprocess.DEVNULL, preexec_fn=limit_memory)
            code = p.returncode
        except subprocess.TimeoutExpired:
            code = TIMEOUT_CODE
        texts = []
        for f in (out, err):
            f.seek(0)
            texts.append(f.read(1 << 20).decode("utf-8", "replace"))
        if code == TIMEOUT_CODE:
            texts[1] += "timeout"
        return code, texts[0], texts[1]


def clause_of(path: Path) -> str:
    first = path.read_text().splitlines()[0]
    m = re.search(r"N1570 (\S+)", first)
    return m.group(1) if m else "?"


def run_probe(src: Path, name: str, clause: str, tmp: Path) -> dict:
    res = {"name": name, "clause": clause, "kind": "run"}
    ll, exe_h, exe_c = tmp / f"{name}.ll", tmp / f"{name}.h.out", tmp / f"{name}.c.out"
    rc, _, err = run([HCC, str(src), "-o", str(ll)])
    if rc != 0 or "panicked" in err:
        res.update(ok=False, why="hcc rejected: " + (err.strip().splitlines()[0][:200] if err.strip() else "no message"))
        return res
    rc, _, err = run([CLANG, "-w", str(ll), "-o", str(exe_h)] + LIBS)
    if rc != 0:
        res.update(ok=False, why="link of hcc IR failed: " + err.strip()[:200])
        return res
    rc, _, err = run([CLANG] + CLANG_FLAGS + [str(src), "-o", str(exe_c)] + LIBS)
    if rc != 0:
        res.update(ok=False, why="clang -std=c11 -pedantic-errors rejected: " + err.strip()[:200])
        return res
    hr = run([str(exe_h)], cwd=tmp)
    cr = run([str(exe_c)], cwd=tmp)
    for who, result in (("hcc", hr), ("clang", cr)):
        if result[0] == TIMEOUT_CODE:
            res.update(ok=False, why=f"the {who} build timed out")
            return res
    if hr[:2] != cr[:2]:
        res.update(ok=False, why=f"differs: hcc exit {hr[0]} vs clang {cr[0]}; hcc out {hr[1][-200:]!r}; clang out {cr[1][-200:]!r}")
        return res
    if "FAIL" in hr[1]:
        res.update(ok=False, why="self-check: " + hr[1].strip()[:300])
        return res
    res.update(ok=True, why="")
    return res


def diag_cases(path: Path):
    prelude, cases, cur = [], [], None
    for line in path.read_text().splitlines():
        m = MARK.match(line)
        if m:
            cur = {"clause": m.group(1), "policy": bool(m.group(2)), "desc": m.group(3), "lines": []}
            cases.append(cur)
        elif cur is None:
            prelude.append(line)
        else:
            cur["lines"].append(line)
    for i, c in enumerate(cases, 1):
        yield i, c, "\n".join(prelude) + "\n" + "\n".join(c["lines"]) + "\n"


def diag_probe(text: str, name: str, clause: str, desc: str, policy: bool, tmp: Path) -> dict:
    src = tmp / f"{name}.c"
    src.write_text(text)
    res = {"name": name, "clause": clause, "kind": "diag", "desc": desc, "policy": policy}
    rc, _, err = run([HCC, str(src), "-o", str(tmp / f"{name}.ll")])
    if "panicked" in err:
        res.update(ok=False, hcc="panic", clang="-", why="hcc panicked")
        return res
    if rc == TIMEOUT_CODE:
        res.update(ok=False, hcc="timeout", clang="-", why="hcc timed out")
        return res
    if rc < 0:
        res.update(ok=False, hcc="signal", clang="-", why=f"hcc was killed by signal {-rc}")
        return res
    hcc = "error" if rc != 0 else ("warning" if "warning" in err else "accepted")
    rc, _, cerr = run([CLANG] + CLANG_FLAGS + ["-fsyntax-only", str(src)])
    if rc == TIMEOUT_CODE:
        clang = "timeout"
    else:
        clang = "error" if rc != 0 else ("warning" if "warning" in cerr else "accepted")
    res.update(hcc=hcc, clang=clang, ok=hcc != "accepted",
               why="" if hcc != "accepted" else "no diagnostic from hcc",
               message=err.strip().splitlines()[0][:200] if err.strip() else "")
    return res


def limit_programs():
    """Programs at the minimum translation limits of 5.2.4.1."""
    out = {}
    n = 127
    out["blocks-127"] = "int main(void){int x=0;" + "{" * n + "x++;" + "}" * n + "return x-1;}\n"
    out["paren-63"] = "int main(void){int x=" + "(" * 63 + "1" + ")" * 63 + ";return x-1;}\n"
    out["cond-incl-63"] = "".join(f"#if {i}+1\n" for i in range(63)) + "int ok=1;\n" + "#endif\n" * 63 + "int main(void){return ok-1;}\n"
    out["declarators-12"] = "int main(void){int x=1;" + "int " + "*" * 12 + "p=0;(void)p;return x-1;}\n"
    out["nested-decl-63"] = "".join("struct s%d{" % i for i in range(63)) + "int v;" + "".join("}m%d;" % i for i in reversed(range(63))) + "int main(void){return 0;}\n"
    ident = "a" * 62 + "%s"
    out["internal-ident-63"] = "int main(void){int %s=1,%s=2;return %s+%s-3;}\n" % (ident % "x", ident % "y", ident % "x", ident % "y")
    out["external-ident-31"] = "int %s=1,%s=2;int main(void){return %s+%s-3;}\n" % ("b" * 30 + "x", "b" * 30 + "y", "b" * 30 + "x", "b" * 30 + "y")
    out["block-ident-511"] = "int main(void){" + "".join(f"int v{i}={i};" for i in range(511)) + "return v510-510;}\n"
    out["external-ids-4095"] = "".join(f"int g{i};" for i in range(4095)) + "int main(void){return g4094;}\n"
    out["macros-4095"] = "".join(f"#define M{i} {i}\n" for i in range(4095)) + "int main(void){return M4094-4094;}\n"
    params = ",".join(f"int p{i}" for i in range(127))
    out["params-127"] = f"int f({params}){{return p0+p126;}}\nint main(void){{return f({','.join(str(i) for i in range(127))})-126;}}\n"
    mp = ",".join(f"p{i}" for i in range(127))
    out["macro-params-127"] = f"#define F({mp}) (p0+p126)\nint main(void){{return F({','.join(str(i) for i in range(127))})-126;}}\n"
    out["string-4095"] = "int printf(const char*,...);\nint main(void){static const char s[]=\"" + "x" * 4095 + "\";return (int)sizeof s-4096;}\n"
    out["object-32767"] = "static char big[32767];int main(void){big[32766]=1;return big[32766]-1;}\n"
    out["members-1023"] = "struct s{" + "".join(f"int m{i};" for i in range(1023)) + "};int main(void){struct s x={0};x.m1022=1;return x.m1022-1;}\n"
    out["enum-1023"] = "enum e{" + ",".join(f"E{i}" for i in range(1023)) + "};int main(void){return E1022-1022;}\n"
    out["case-1023"] = "int f(int x){switch(x){" + "".join(f"case {i}:return {i};" for i in range(1023)) + "}return -1;}\nint main(void){return f(1022)-1022;}\n"
    out["struct-nest-63"] = "".join("struct{" for _ in range(63)) + "int v;" + "".join(f"}}n{i};" for i in range(62)) + "}top;int main(void){return 0;}\n"
    out["logical-line-4095"] = "int main(void){int x=0" + "+1" * 2040 + ";return x-2040;}\n"
    return out


def known_gaps() -> dict:
    gaps = {}
    path = ROOT / "conformance" / "known_gaps.txt"
    for line in path.read_text().splitlines() if path.exists() else []:
        if line.strip() and not line.startswith("#"):
            file, desc, reason = (part.strip() for part in line.split("|", 2))
            gaps[(Path(file).stem, desc)] = reason
    return gaps


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--json", help="write the results to this file")
    ap.add_argument("-j", type=int, default=os.cpu_count() or 2)
    ap.add_argument("filter", nargs="?", default="")
    args = ap.parse_args()
    jobs = []
    with tempfile.TemporaryDirectory(prefix="hcc-conf-") as td:
        tmp = Path(td)
        for p in sorted((ROOT / "conformance" / "run").glob("*.c")):
            jobs.append(lambda p=p: run_probe(p, p.stem, clause_of(p), tmp))
        for p in sorted((ROOT / "conformance" / "diag").glob("*.c")):
            for i, c, text in diag_cases(p):
                nm = f"{p.stem}.{i}"
                jobs.append(lambda t=text, nm=nm, c=c: diag_probe(t, nm, c["clause"], c["desc"], c["policy"], tmp))
        # 5.2.4.1: 15 nesting levels for #include files.
        for level in range(15):
            nxt = f'#include "nest{level + 1}.h"\n' if level < 14 else "#define NEST_DEPTH 15\n"
            (tmp / f"nest{level}.h").write_text(nxt)
        (tmp / "limit-include-15.c").write_text('#include "nest0.h"\nint main(void){return NEST_DEPTH-15;}\n')
        jobs.append(lambda: run_probe(tmp / "limit-include-15.c", "limit-include-15", "5.2.4.1", tmp))
        for nm, text in limit_programs().items():
            src = tmp / f"limit-{nm}.c"
            src.write_text(text)
            jobs.append(lambda src=src, nm=nm: run_probe(src, "limit-" + nm, "5.2.4.1", tmp))
        with ThreadPoolExecutor(args.j) as ex:
            results = [r for r in ex.map(lambda f: f(), jobs) if re.search(args.filter, r["name"])]
    gaps = known_gaps()
    for r in results:
        reason = gaps.get((r["name"].rsplit(".", 1)[0], r.get("desc", "")))
        # Only the documented failure is exempt: hcc accepting the case
        # silently. A timeout, panic or signal still fails the run.
        if reason is not None and (r["ok"] or r.get("hcc") == "accepted"):
            r["known"] = reason
    fails = [r for r in results if not r["ok"] and "known" not in r]
    fixed = [r for r in results if r["ok"] and "known" in r]
    for r in results:
        status = "PASS" if r["ok"] else ("KNOWN" if "known" in r else "FAIL")
        if r["kind"] == "diag":
            print(f"{status} {r['clause']:<12} {r['name']:<28} hcc={r['hcc']:<8} clang={r['clang']:<8} {r['desc']}")
        else:
            print(f"{status} {r['clause']:<12} {r['name']:<28} {r['why']}")
    for r in fixed:
        print(f"NOW PASSES (remove from conformance/known_gaps.txt): {r['name']} {r.get('desc', '')}")
    runs = [r for r in results if r["kind"] == "run"]
    required = [r for r in results if r["kind"] == "diag" and not r["policy"]]
    policy = [r for r in results if r["kind"] == "diag" and r["policy"]]
    counted = runs + required
    passed = sum(r["ok"] for r in counted)
    known = sum("known" in r and not r["ok"] for r in counted)

    def clang_counts(rows):
        return (f"clang errors on {sum(r['clang'] == 'error' for r in rows)}, warns on {sum(r['clang'] == 'warning' for r in rows)}, "
                f"accepts {sum(r['clang'] == 'accepted' for r in rows)}, times out on {sum(r['clang'] == 'timeout' for r in rows)}")

    print(f"\nconformance: {passed}/{len(counted)} pass, {known} known gaps "
          f"({sum(r['ok'] for r in runs)}/{len(runs)} programs, {sum(r['ok'] for r in required)}/{len(required)} required diagnostics; "
          f"{clang_counts(required)})")
    print(f"policy (no diagnostic required): {sum(r['ok'] for r in policy)}/{len(policy)} diagnosed by hcc ({clang_counts(policy)})")
    unexpected = len(fails) + len(fixed)
    if unexpected:
        print(f"{len(fails)} unexpected failures, {len(fixed)} known gaps now passing")
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=1) + "\n")
    return 1 if fails or fixed else 0


if __name__ == "__main__":
    sys.exit(main())
